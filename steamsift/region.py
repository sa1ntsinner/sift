"""Store regions: countries, price groups, local price formatting, IP hint.

data/regions.json was generated by probing the Steam store for every ISO country
code with fingerprint games. It records whether a store exists, the USD price
group (US, MENA, CIS, LATAM, South Asia all show "$" but charge different
prices), and one real formatted price used to learn the local number format.
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass
from functools import lru_cache
from importlib.resources import files

import requests

from .net import USER_AGENT


@lru_cache(maxsize=1)
def _data() -> dict[str, dict]:
    return json.loads((files("steamsift") / "data" / "regions.json").read_text(encoding="utf-8"))


def info(code: str) -> dict | None:
    return _data().get((code or "").upper())


def has_store(code: str) -> bool:
    i = info(code)
    return bool(i and i.get("store"))


def name(code: str, lang: str = "en") -> str:
    i = info(code)
    return (i.get(lang) or i.get("en")) if i else (code or "?")


def currency_marker(code: str) -> str:
    """'$', '€', '₸', 'R$', 'CHF', 'руб' … taken from the real Steam price format."""
    i = info(code)
    if not i or not i.get("sample"):
        return ""
    return re.sub(r"[\d\s.,\u00a0\u202f']+", " ", i["sample"][0]).strip()


def group(code: str) -> str | None:
    i = info(code)
    return i.get("group") if i else None


def label(code: str, lang: str = "en") -> str:
    """Human label: 'Турция · MENA-USD', 'Kazakhstan · ₸', 'Germany · €'."""
    g = group(code)
    tail = g if g and g != "USD" else ("USD" if g == "USD" else currency_marker(code))
    return f"{name(code, lang)} · {tail}" if tail else name(code, lang)


def search(query: str, lang: str = "en") -> list[str]:
    """Country codes matching a code or (part of) an English/Russian name, best first."""
    q = query.strip().lower()
    if not q:
        return []
    if len(q) == 2 and q.upper() in _data():
        return [q.upper()]
    scored = []
    for code, i in _data().items():
        names = [i.get("en", "").lower(), i.get("ru", "").lower()]
        if any(n == q for n in names):
            scored.append((0, code))
        elif any(n.startswith(q) for n in names):
            scored.append((1, code))
        elif any(q in n for n in names):
            scored.append((2, code))
    return [c for _, c in sorted(scored, key=lambda x: (x[0], name(x[1], lang)))]


def detect_ip_country(timeout: int = 6) -> str | None:
    """Country Steam assigns to this IP. Only a hint: prices follow the *account's* region."""
    try:
        r = requests.get("https://store.steampowered.com/", headers={"User-Agent": USER_AGENT},
                         timeout=timeout, stream=True)
        r.close()
        raw = r.cookies.get("steamCountry", "")
        code = requests.utils.unquote(raw).split("|")[0].upper()
        return code if len(code) == 2 else None
    except requests.RequestException:
        return None


# --------------------------------------------------------------------------- price formatting

_NUM = re.compile(r"\d(?:[\d.,\s\u00a0\u202f']*\d)?")


@dataclass(frozen=True)
class PriceFormat:
    prefix: str = "$"
    suffix: str = ""
    decimals: int = 2
    dec_sep: str = "."
    thou_sep: str = ","

    @classmethod
    def learn(cls, formatted: str, cents: int) -> "PriceFormat":
        matches = list(_NUM.finditer(formatted or ""))
        if not matches:
            return cls()
        m = max(matches, key=lambda x: len(x.group()))
        num = m.group()
        digits = int(re.sub(r"\D", "", num) or 0)
        if digits == cents and len(num) >= 3 and not num[-3].isdigit():
            decimals = 2
        elif digits * 100 == cents:
            decimals = 0
        else:
            decimals = 2 if re.search(r"[.,]\d\d$", num) else 0
        dec_sep = num[-3] if decimals == 2 else ""
        int_part = num[:-3] if decimals == 2 else num
        seps = [c for c in int_part if not c.isdigit()]
        if seps:
            thou = seps[0]
        elif len(int_part) >= 4:
            thou = ""               # e.g. RU: "3599 руб" — no grouping at all
        elif dec_sep == ",":
            thou = " "
        elif dec_sep == ".":
            thou = ","
        else:
            thou = ","
        return cls(formatted[: m.start()], formatted[m.end():], decimals, dec_sep or ".", thou)

    def format(self, cents: int) -> str:
        if self.decimals == 2:
            whole, frac = divmod(int(round(cents)), 100)
            body = f"{whole:,}".replace(",", self.thou_sep) + self.dec_sep + f"{frac:02d}"
        else:
            body = f"{int(round(cents / 100)):,}".replace(",", self.thou_sep)
        return f"{self.prefix}{body}{self.suffix}"

    def amount(self, value: float) -> str:
        """Format a user-entered amount in local units (e.g. a budget of 1500 ₸)."""
        return self.format(round(value * 100))


@lru_cache(maxsize=64)
def price_format(code: str) -> PriceFormat:
    i = info(code)
    if i and i.get("sample"):
        return PriceFormat.learn(i["sample"][0], int(i["sample"][1]))
    return PriceFormat()
